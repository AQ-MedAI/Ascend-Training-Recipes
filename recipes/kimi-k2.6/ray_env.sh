#!/usr/bin/env bash
# Source after runtime_env.sh. Forward resolved values without replacing them on workers.
K26_RUNTIME_ENV_ARGS=()
K26_RUNTIME_ENV_NAMES=(
    LD_LIBRARY_PATH ASCEND_CUSTOM_OPP_PATH ASCEND_HOME_PATH ASCEND_OPP_PATH
    ASCEND_AICPU_PATH ASCEND_TOOLKIT_HOME ASCEND_TOOLKIT_LATEST_HOME
    ATB_HOME_PATH TOOLCHAIN_HOME CMAKE_PREFIX_PATH ASCEND_RUNTIME_OPTIONS
    HCCL_HOST_SOCKET_PORT_RANGE HCCL_NPU_SOCKET_PORT_RANGE HCCL_CONNECT_TIMEOUT
    HCCL_OP_EXPANSION_MODE HCCL_BUFFSIZE GROUP_HCCL_BUFFER_SIZE P2P_HCCL_BUFFSIZE
    HF_HOME HF_HUB_OFFLINE TRANSFORMERS_OFFLINE VLLM_USE_V1 TASK_QUEUE_ENABLE
    RAY_EXPERIMENTAL_NOSET_ASCEND_RT_VISIBLE_DEVICES
    ASCEND_LAUNCH_BLOCKING PYTHONFAULTHANDLER
    PYTORCH_NPU_ALLOC_CONF PYTORCH_CUDA_ALLOC_CONF
    OMP_NUM_THREADS MKL_NUM_THREADS NUMEXPR_NUM_THREADS
    VERL_ROOT PYTHONPATH MINDSPEED_ROOT MEGATRON_ROOT MEGATRON_BRIDGE_ROOT
    ASCEND_CHECKPOINT_WRITER TRANSFORMERS_VERBOSITY
    WANDB_MODE WANDB_DIR WANDB_ENTITY TENSORBOARD_DIR
)
for _k26_name in "${K26_RUNTIME_ENV_NAMES[@]}"; do
    _k26_value="${!_k26_name:-}"
    [[ -n "$_k26_value" ]] || continue
    K26_RUNTIME_ENV_ARGS+=("++ray_kwargs.ray_init.runtime_env.env_vars.${_k26_name}='${_k26_value}'")
done
unset _k26_name _k26_value
